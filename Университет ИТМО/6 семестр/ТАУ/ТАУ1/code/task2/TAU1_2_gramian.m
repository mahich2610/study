clc; clear;

% матрицы
A = [1 2 -1; -6 -7 -2; 6 6 1];
B = [2; 0; 0];
t1 = 3;

% вычисление Грамиана
% P = int_0^t1 exp(A*t)*B*B'*exp(A'*t) dt
gramian_fun = @(t) expm(A*t) * B * B' * expm(A'*t);
W = integral(gramian_fun, 0, t1, 'ArrayValued', true);

disp('=== Грамиан управляемости W ===');
disp(W);

% собственные числа Грамиана
ev = eig(W);
disp('Собственные числа Грамиана:');
disp(ev);

% простая проверка знака
if all(ev > 0)
    disp('-> Все собственные числа > 0: система полностью управляема');
else
    disp('-> Внимание: есть нулевые или отрицательные числа');
end