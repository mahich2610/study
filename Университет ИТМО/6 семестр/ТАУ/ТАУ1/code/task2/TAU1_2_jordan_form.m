clc; clear;
% матрицы 
A = [1 2 -1; -6 -7 -2; 6 6 1];
B = [2; 0; 0];

% собственные числа и векторы
[V, D] = eig(A);
lambda = diag(D);  % столбец собственных чисел

% берем векторы из столбцов v
v_c = V(:,1);   % комплексный вектор
v_r = V(:,3);   % вещественный вектор

% разбиваем комплексный вектор на вещественную и мнимую части
p1 = real(v_c);
p2 = imag(v_c);
p3 = v_r;

% матрица перехода P
P = [p1, p2, p3];

% обратная матрица
P_inv = inv(P);

% жорданова форма J = P^-1 * A * P
J = P_inv * A * P;

% вектор управления в новом базисе
B_tilde = P_inv * B;

% вывод результатов
disp('--- Результаты ---');
disp('Матрица P:'); disp(P);
disp('Матрица P^-1:'); disp(P_inv);
disp('Жорданова форма J:'); disp(J);
disp('Вектор B_tilde:'); disp(B_tilde);

% проверка управляемости по строкам B_tilde
disp('--- Проверка управляемости ---');
if B_tilde(1) ~= 0 || B_tilde(2) ~= 0
    disp('Блок J1 (комплексные корни) -> УПРАВЛЯЕМ');
else
    disp('Блок J1 (комплексные корни) -> НЕ управляем'); 
end

tolerance = 1e-6;  % допуск

if abs(B_tilde(3)) > tolerance
    disp('Блок J2 (вещественный корень) -> УПРАВЛЯЕМ');
else
    disp('Блок J2 (вещественный корень) -> НЕ управляем');
end