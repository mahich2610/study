clc; clear;

% матрицы
A = [-9 0 -10; -4 -1 -6; 6 -2 5];
C = [2 -1 2];

% построение матрицы наблюдаемости V
V = [C; C*A; C*A^2];

% вывод результатов
disp('=== Матрица наблюдаемости V ===');
disp('V =');
disp(V);

% находим ранг
rank_V = rank(V);
disp(['rank(V) = ', num2str(rank_V)]);

% проверка наблюдаемости
if rank_V == 3
    disp('-> Система ПОЛНОСТЬЮ наблюдаема');
else
    disp('-> Система НЕ ПОЛНОСТЬЮ наблюдаема');
end