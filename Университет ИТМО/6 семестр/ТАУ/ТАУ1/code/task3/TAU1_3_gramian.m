clc; clear;

% матрицы
A = [-9 0 -10; -4 -1 -6; 6 -2 5];
C = [2 -1 2];
t1 = 3;

% подынтегральная функция: exp(A'*t) * C' * C * exp(A*t)
integrand = @(t) expm(A'*t) * C' * C * expm(A*t);

% численное интегрирование от 0 до t1
Q = integral(integrand, 0, t1, 'ArrayValued', true);

% вывод результатов
disp('=== Грамиан наблюдаемости Q(t1) ===');
disp('Q =');
disp(Q);

% собственные числа
eig_Q = eig(Q);
disp('Собственные числа Грамиана:');
disp(eig_Q);

% анализ
if all(eig_Q > 0)
    disp('-> Все собственные числа > 0: система ПОЛНОСТЬЮ наблюдаема');
else
    disp('-> Внимание: есть нулевые или отрицательные числа');
end

C = [0 -5 -5];