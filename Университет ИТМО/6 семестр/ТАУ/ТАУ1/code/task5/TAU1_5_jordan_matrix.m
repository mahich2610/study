clc; clear; close all;

%% матрицы
A = [1 2 -1; -6 -7 -2; 6 6 1];
B = [-2; 4; -2];
C = [0 1 -1; 0 -3 3];

disp('========================================');
disp('  ЖОРДАНОВА ФОРМА И АНАЛИЗ СИСТЕМЫ');
disp('========================================');

%% собственные числа и векторы
[V, D] = eig(A);
lambda = diag(D);

disp(' ');
disp('Собственные числа:');
disp(lambda);

%% ищем комплексный и вещественный векторы
v_c = [];  % комплексный вектор
v_r = [];  % вещественный вектор

for k = 1:3
    if abs(imag(lambda(k))) > 0.01 && isempty(v_c)
        v_c = V(:, k);   % комплексный вектор
    elseif abs(imag(lambda(k))) < 0.01 && isempty(v_r)
        v_r = real(V(:, k));  % вещественный вектор
    end
end

%% разбиваем комплексный вектор на вещественную и мнимую части
p1 = real(v_c);
p2 = imag(v_c);
p3 = v_r;

%% матрица перехода P
P = [p1, p2, p3];

% проверяем, не вырождена ли P
if abs(det(P)) < 1e-10
    disp('ВНИМАНИЕ: Матрица P вырождена! Меняем порядок столбцов...');
    P = [p3, p1, p2];  % другой порядок
end

disp(' ');
disp('Матрица P:'); 
disp(P);
disp('Определитель P:'); 
disp(det(P));

%% обратная матрица
P_inv = inv(P);

%% жорданова форма J = P^-1 * A * P
J = P_inv * A * P;

%% вектор управления в новом базисе
B_tilde = P_inv * B;

%% матрица выхода в новом базисе
C_tilde = C * P;

%% вывод результатов
disp(' ');
disp('========================================');
disp('  РЕЗУЛЬТАТЫ');
disp('========================================');
disp(' ');
disp('Жорданова форма J:'); 
disp(J);
disp(' ');
disp('Вектор B_tilde:'); 
disp(B_tilde);
disp(' ');
disp('Матрица C_tilde:'); 
disp(C_tilde);

%% проверка управляемости
disp(' ');
disp('========================================');
disp('  ПРОВЕРКА УПРАВЛЯЕМОСТИ');
disp('========================================');

tolerance = 1e-6;

if abs(B_tilde(1)) > tolerance || abs(B_tilde(2)) > tolerance
    disp('Блок J1 (комплексные корни) -> УПРАВЛЯЕМ');
    controllable_1 = true;
else
    disp('Блок J1 (комплексные корни) -> НЕ управляем');
    controllable_1 = false;
end

if abs(B_tilde(3)) > tolerance
    disp('Блок J2 (вещественный корень) -> УПРАВЛЯЕМ');
    controllable_2 = true;
else
    disp('Блок J2 (вещественный корень) -> НЕ управляем');
    controllable_2 = false;
end

%% проверка наблюдаемости
disp(' ');
disp('========================================');
disp('  ПРОВЕРКА НАБЛЮДАЕМОСТИ');
disp('========================================');

% для блока J1 (2x2) проверяем первые две строки C_tilde
if any(abs(C_tilde(:,1:2)) > tolerance, 'all')
    disp('Блок J1 (комплексные корни) -> НАБЛЮДАЕМ');
    observable_1 = true;
else
    disp('Блок J1 (комплексные корни) -> НЕ наблюдаем');
    observable_1 = false;
end

% для блока J2 (1x1) проверяем третий столбец C_tilde
if any(abs(C_tilde(:,3)) > tolerance)
    disp('Блок J2 (вещественный корень) -> НАБЛЮДАЕМ');
    observable_2 = true;
else
    disp('Блок J2 (вещественный корень) -> НЕ наблюдаем');
    observable_2 = false;
end

%% общий вывод
disp(' ');
disp('========================================');
disp('  ОБЩИЙ ВЫВОД');
disp('========================================');

if controllable_1 && controllable_2
    disp('СИСТЕМА ПОЛНОСТЬЮ УПРАВЛЯЕМА');
else
    disp('СИСТЕМА НЕ ПОЛНОСТЬЮ УПРАВЛЯЕМА');
end

if observable_1 && observable_2
    disp('СИСТЕМА ПОЛНОСТЬЮ НАБЛЮДАЕМА');
else
    disp('СИСТЕМА НЕ ПОЛНОСТЬЮ НАБЛЮДАЕМА');
end

disp(' ');