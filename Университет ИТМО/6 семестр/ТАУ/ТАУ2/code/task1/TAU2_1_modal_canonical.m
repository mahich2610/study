%% листинг А.6. расчет матрицы перехода в каноническую управляемую форму
clc; clear; close all;

% управляемая подсистема в жордановом базисе (из листинга А.1)
Ac_hat = [2, 3; -3, 2];
Bc_hat = [0; 2];

% матрица управляемости исходной (усеченной) системы в жордановом базисе
Uc_hat = ctrb(Ac_hat, Bc_hat);

% каноническая управляемая форма для полинома lambda^2 - 4*lambda + 13
A_upr = [0, 1; -13, 4];
B_upr = [0; 1];

% матрица управляемости системы в канонической управляемой форме
Uc_star = ctrb(A_upr, B_upr);

% матрица перехода: P_upr = Uc_star * inv(Uc_hat)
P_upr = Uc_star * inv(Uc_hat);

disp('=== матрица перехода P_upr ===');
disp(P_upr);