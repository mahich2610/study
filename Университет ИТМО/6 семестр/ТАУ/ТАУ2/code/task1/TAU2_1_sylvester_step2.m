%% Листинг А.2. Решение уравнения Сильвестра для управляемой подсистемы
clc; clear; close all;

% возьмем управляемую подсистему из предыдущего листинга
Ac = [2, 3; -3, 2];
Bc = [0; 2];

% зададим параметры уравнения Сильвестра
% жорданова клетка для кратных полюсов {-3, -3}
Gamma = [-3, 1; 0, -3];
% вспомогательная наблюдаемая матрица
Y = [1, 2];

% вычислим правую часть уравнения: Q = Bc * Y
Q = Bc * Y;

% преобразуем матричное уравнение Ac*P - P*Gamma = Q в систему линейных уравнений
% используем тождество: vec(Ac*P - P*Gamma) = (I kron Ac - Gamma' kron I) vec(P)
n = size(Ac, 1);
M_op = kron(eye(n), Ac) - kron(Gamma', eye(n));
vec_Q = Q(:);

% решим полученную систему линейных уравнений
vec_P = M_op \ vec_Q;

% вернем матричную форму P
P_silv = reshape(vec_P, n, n);

% найдем регулятор подсистемы по формуле Kc = -Y * inv(P)
Kc = -Y * inv(P_silv);

% выведем результаты на экран
disp('=== Матрица P (решение уравнения Сильвестра) ===');
disp(P_silv);

disp('=== Регулятор подсистемы Kc ===');
disp(Kc);