%% Листинг А.1. Переход в жорданов базис и выделение управляемой подсистемы
clc; clear; close all;

% исходные матрицы системы
A = [5 8 5; -6 -9 -8; 6 6 5];
B = [2; 0; 0];

% собственные векторы (нашли аналитически)
v1 = [-1; 1; 0];              % для lambda_1 = -3
v2_complex = [1 + 1i; -2; 2]; % для lambda_2,3 = 2 +/- 3i

% составим матрицу перехода P_tr из вещественного базиса
% столбцы: v1, Re(v2), Im(v2)
P_tr = [v1, real(v2_complex), imag(v2_complex)];

% найдем обратную матрицу перехода
P_tr_inv = inv(P_tr);

% сделаем преобразование подобия для матрицы состояния
J_r = P_tr_inv * A * P_tr;

% сделаем преобразование подобия для матрицы управления
B_tilde = P_tr_inv * B;

% выведем результаты на экран
disp('=== Матрица перехода P_tr ===');
disp(P_tr);

disp('=== Обратная матрица P_tr^(-1) ===');
disp(P_tr_inv);

disp('=== Вещественная жорданова форма J_r ===');
disp(J_r);

disp('=== Преобразованная матрица управления B_tilde ===');
disp(B_tilde);

% выделим управляемую подсистему (уберем неуправляемую моду -3)
A_c = J_r(2:3, 2:3);
B_c = B_tilde(2:3);

disp('=== Управляемая подсистема A_c ===');
disp(A_c);

disp('=== Управляемая подсистема B_c ===');
disp(B_c);