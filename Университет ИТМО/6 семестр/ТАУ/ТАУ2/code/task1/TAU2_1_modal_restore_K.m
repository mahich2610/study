%% Листинг А.7. Восстановление полной матрицы регулятора K
clc; clear; close all;

% регулятор в каноническом базисе (из уравнений -13+k1=-9000, 4+k2=-330)
K_upr = [-8987, -334];

% матрица перехода (из Листинга А.6)
P_upr = [1/6, 0; 1/3, 1/2];

% переход к жорданову базису: Kc_hat = K_upr * P_upr
Kc_hat = K_upr * P_upr;

disp('=== регулятор Kc_hat в жордановом базисе ===');
disp(Kc_hat);

% матрица перехода в жорданов базис (из Листинга А.1)
P_tr = [-1, 1, 1; 1, -2, 0; 0, 2, 0];
P_tr_inv = inv(P_tr);

% формируем полный вектор в базисе Jr
% дополняем нулем слева для неуправляемой моды lambda_1 = -3
K_full_tilde = [0, Kc_hat(1), Kc_hat(2)];

% обратное преобразование подобия в исходный базис
K_modal = K_full_tilde * P_tr_inv;

disp('=== полная матрица регулятора K (метод модального управления) ===');
disp(K_modal);