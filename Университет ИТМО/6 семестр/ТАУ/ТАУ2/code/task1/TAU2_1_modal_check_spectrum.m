%% Листинг А.8. Проверка спектра замкнутой системы
clc; clear; close all;

% исходные данные системы
A = [5, 8, 5; -6, -9, -8; 6, 6, 5];
B = [2; 0; 0];

% синтезированный регулятор методом модального управления (из Листинга А.7)
K = [-167, -167, -888.0833];

% формируем матрицу замкнутой системы
A_cl = A + B * K;

% вычисляем собственные числа
eig_cl = eig(A_cl);

disp('=== матрица замкнутой системы A+BK ===');
disp(A_cl);

disp('=== собственные числа замкнутой системы ===');
disp(eig_cl);

% верификация совпадения с желаемым спектром {-3, -30, -300}
desired = [-3; -30; -300];
error_val = max(abs(sort(real(eig_cl)) - sort(desired)));

if error_val < 1e-3
    disp('ПРОВЕРКА ПРОЙДЕНА: Спектр совпадает с {-3, -30, -300}');
else
    disp(['ОШИБКА: Максимальное отклонение = ', num2str(error_val)]);
end