%% Листинг А.4. Проверка спектра замкнутой системы
clc; clear; close all;

% возьмем исходные матрицы системы
A = [5 8 5; -6 -9 -8; 6 6 5];
B = [2; 0; 0];

% подставим синтезированную матрицу регулятора из третьего листинга
K = [-5.0000, -5.0000, -3.8334];

% сформируем матрицу замкнутой системы
A_cl = A + B * K;

% вычислим собственные числа полученной матрицы
eig_cl = eig(A_cl);

% выведем результаты на экран
disp('=== Матрица замкнутой системы A+BK ===');
disp(A_cl);

disp('=== Собственные числа замкнутой системы ===');
disp(eig_cl);

% проверим совпадение с желаемым спектром {-3, -3, -3}
desired_spectrum = [-3; -3; -3];
if max(abs(sort(real(eig_cl)) - sort(desired_spectrum))) < 1e-6
    disp('ПРОВЕРКА ПРОЙДЕНА: Спектр совпадает с желаемым {-3, -3, -3}');
else
    disp('ОШИБКА: Спектр не совпадает с желаемым!');
end